using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
using System.Web;
using System.Web.UI;
using System.Web.UI.HtmlControls;
using System.Web.UI.WebControls;

namespace SERVICIOS
{
    // Recorre el árbol de controles (igual que PermisoHelper) y aplica las traducciones
    // según los atributos de cada control:
    //   data-traduccion             -> texto del control (Label, Button, LinkButton, CheckBox, HyperLink, <p>, <h2>, <a>...)
    //   data-traduccion-placeholder -> placeholder de un TextBox
    //   data-traduccion-title       -> tooltip (title)
    //   data-traduccion-vacio       -> EmptyDataText de un GridView
    //   AccessibleHeaderText        -> encabezado de una columna de GridView
    //   data-traduccion en ListItem -> texto de cada opción de una lista
    // Los textos que ASP.NET renderiza sin codificar (Label, LinkButton, encabezados...) se codifican con Html().
    public static class TraductorHelper
    {
        public const string ClaveSeleccionar = "comun_btnSeleccionar";

        public static void Traducir(Control raiz, Dictionary<string, string> traducciones, Control excluir = null)
        {
            if (raiz == null || traducciones == null || traducciones.Count == 0) return;

            foreach (Control ctrl in raiz.Controls)
            {
                if (ctrl == excluir) continue;

                TraducirControl(ctrl, traducciones);

                if (ctrl.HasControls())
                    Traducir(ctrl, traducciones, excluir);
            }
        }

        private static void TraducirControl(Control ctrl, Dictionary<string, string> traducciones)
        {
            string texto;

            // Tooltip
            if (Buscar(traducciones, LeerAtributo(ctrl, "data-traduccion-title"), out texto))
                EscribirAtributo(ctrl, "title", texto);

            // TextBox: solo el placeholder, nunca el texto que escribió el usuario
            TextBox txt = ctrl as TextBox;
            if (txt != null)
            {
                if (Buscar(traducciones, txt.Attributes["data-traduccion-placeholder"], out texto))
                    txt.Attributes["placeholder"] = texto;
                return;
            }

            // Listas: cada opción con su propio data-traduccion
            ListControl lista = ctrl as ListControl;
            if (lista != null)
            {
                foreach (ListItem item in lista.Items)
                {
                    if (Buscar(traducciones, item.Attributes["data-traduccion"], out texto))
                    {
                        item.Value = item.Value;   // fija el Value: si no tenía, el Value es el Text y cambiaría al traducir
                        item.Text = texto;
                    }
                }
                return;
            }

            GridView grilla = ctrl as GridView;
            if (grilla != null)
            {
                TraducirGrilla(grilla, traducciones);
                return;
            }

            if (!Buscar(traducciones, LeerAtributo(ctrl, "data-traduccion"), out texto))
                return;

            BaseValidator validador = ctrl as BaseValidator;        // RequiredFieldValidator, CompareValidator...
            if (validador != null) { validador.ErrorMessage = Html(texto); return; }

            Button boton = ctrl as Button;                          // el Text de un Button va en el atributo value (ASP.NET ya lo codifica)
            if (boton != null) { boton.Text = texto; return; }

            IButtonControl otroBoton = ctrl as IButtonControl;      // LinkButton
            if (otroBoton != null) { otroBoton.Text = Html(texto); return; }

            ITextControl conTexto = ctrl as ITextControl;           // Label, Literal
            if (conTexto != null) { conTexto.Text = Html(texto); return; }

            CheckBox check = ctrl as CheckBox;                      // CheckBox, RadioButton
            if (check != null) { check.Text = Html(texto); return; }

            HyperLink link = ctrl as HyperLink;
            if (link != null) { link.Text = Html(texto); return; }

            HtmlContainerControl html = ctrl as HtmlContainerControl; // <p>, <h2>, <span>, <label>, <a>, <li>... con runat="server"
            if (html != null) html.InnerText = texto;
        }

        private static void TraducirGrilla(GridView grilla, Dictionary<string, string> traducciones)
        {
            string texto;

            // Si hay botón "Seleccionar" autogenerado, ocupa la primera celda de cada fila
            int desfasaje = grilla.AutoGenerateSelectButton || grilla.AutoGenerateEditButton || grilla.AutoGenerateDeleteButton ? 1 : 0;

            for (int i = 0; i < grilla.Columns.Count; i++)
            {
                DataControlField columna = grilla.Columns[i];
                if (!Buscar(traducciones, columna.AccessibleHeaderText, out texto)) continue;
                texto = Html(texto);

                if (columna.HeaderText != texto)
                    columna.HeaderText = texto;

                // Si la grilla ya se bindeó, el encabezado ya está armado: se actualiza la celda también
                if (grilla.HeaderRow != null && grilla.HeaderRow.Cells.Count > i + desfasaje)
                {
                    TableCell celda = grilla.HeaderRow.Cells[i + desfasaje];
                    if (!celda.HasControls())       // si tiene LinkButton de ordenamiento no se toca
                        celda.Text = texto;
                }
            }

            // Texto del botón "Seleccionar" autogenerado (clave común a todas las páginas)
            if (grilla.AutoGenerateSelectButton && Buscar(traducciones, ClaveSeleccionar, out texto))
            {
                texto = Html(texto);
                foreach (GridViewRow fila in grilla.Rows)
                {
                    if (fila.Cells.Count == 0) continue;
                    foreach (Control c in fila.Cells[0].Controls)
                    {
                        IButtonControl btn = c as IButtonControl;
                        if (btn != null && btn.CommandName == "Select")
                            btn.Text = texto;
                    }
                }
            }

            // Texto de grilla vacía
            if (Buscar(traducciones, grilla.Attributes["data-traduccion-vacio"], out texto))
            {
                texto = Html(texto);
                grilla.EmptyDataText = texto;

                if (grilla.HasControls() && grilla.Controls[0].HasControls())
                {
                    foreach (Control c in grilla.Controls[0].Controls)
                    {
                        GridViewRow fila = c as GridViewRow;
                        if (fila != null && fila.RowType == DataControlRowType.EmptyDataRow && fila.Cells.Count > 0)
                            fila.Cells[0].Text = texto;
                    }
                }
            }
        }

        private static string Html(string texto)
        {
            return HttpUtility.HtmlEncode(texto);
        }

        private static bool Buscar(Dictionary<string, string> traducciones, string clave, out string texto)
        {
            texto = null;
            return !string.IsNullOrEmpty(clave) && traducciones.TryGetValue(clave, out texto) && !string.IsNullOrEmpty(texto);
        }

        private static string LeerAtributo(Control ctrl, string nombre)
        {
            WebControl wc = ctrl as WebControl;
            if (wc != null) return wc.Attributes[nombre];

            HtmlControl hc = ctrl as HtmlControl;
            if (hc != null) return hc.Attributes[nombre];

            return null;
        }

        private static void EscribirAtributo(Control ctrl, string nombre, string valor)
        {
            WebControl wc = ctrl as WebControl;
            if (wc != null) { wc.Attributes[nombre] = valor; return; }

            HtmlControl hc = ctrl as HtmlControl;
            if (hc != null) hc.Attributes[nombre] = valor;
        }
    }
}
