/* ---------- 1. TABLAS ---------- */
IF OBJECT_ID('dbo.Idioma', 'U') IS NULL
BEGIN
    CREATE TABLE [dbo].[Idioma](
        [ID] [int] IDENTITY(1,1) NOT NULL,
        [Codigo] [nvarchar](10) NOT NULL,
        [Nombre] [nvarchar](50) NOT NULL,
        [Activo] [bit] NOT NULL CONSTRAINT [DF_Idioma_Activo] DEFAULT (1),
        [EsPredeterminado] [bit] NOT NULL CONSTRAINT [DF_Idioma_EsPredeterminado] DEFAULT (0),
        CONSTRAINT [PK_Idioma] PRIMARY KEY CLUSTERED ([ID] ASC),
        CONSTRAINT [UQ_Idioma_Codigo] UNIQUE ([Codigo])
    )
END
GO

IF OBJECT_ID('dbo.Etiqueta', 'U') IS NULL
BEGIN
    CREATE TABLE [dbo].[Etiqueta](
        [ID] [int] IDENTITY(1,1) NOT NULL,
        [Clave] [nvarchar](150) NOT NULL,
        [Descripcion] [nvarchar](200) NULL,
        CONSTRAINT [PK_Etiqueta] PRIMARY KEY CLUSTERED ([ID] ASC),
        CONSTRAINT [UQ_Etiqueta_Clave] UNIQUE ([Clave])
    )
END
GO

IF OBJECT_ID('dbo.Traduccion', 'U') IS NULL
BEGIN
    CREATE TABLE [dbo].[Traduccion](
        [ID_Idioma] [int] NOT NULL,
        [ID_Etiqueta] [int] NOT NULL,
        [Texto] [nvarchar](1000) NOT NULL,
        CONSTRAINT [PK_Traduccion] PRIMARY KEY CLUSTERED ([ID_Idioma] ASC, [ID_Etiqueta] ASC),
        CONSTRAINT [FK_Traduccion_Idioma] FOREIGN KEY ([ID_Idioma]) REFERENCES [dbo].[Idioma] ([ID]),
        CONSTRAINT [FK_Traduccion_Etiqueta] FOREIGN KEY ([ID_Etiqueta]) REFERENCES [dbo].[Etiqueta] ([ID])
    )
END
GO

