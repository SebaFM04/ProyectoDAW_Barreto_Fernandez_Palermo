INSERT INTO [dbo].[Rol_Permiso] ([ID_Rol], [ID_Permiso])
SELECT r.[ID], pe.[ID]
FROM @Permisos p
INNER JOIN [dbo].[Permiso] pe ON pe.[Clave] = p.[Clave]
INNER JOIN [dbo].[Rol] r ON r.[Nombre] = N'Web Master' OR (r.[Nombre] = N'AdminSuper' AND p.[SoloWebMaster] = 0)
WHERE NOT EXISTS (SELECT 1 FROM [dbo].[Rol_Permiso] x WHERE x.[ID_Rol] = r.[ID] AND x.[ID_Permiso] = pe.[ID])
GO

