DECLARE @es int = (SELECT [ID] FROM [dbo].[Idioma] WHERE [Codigo] = N'es')
DECLARE @en int = (SELECT [ID] FROM [dbo].[Idioma] WHERE [Codigo] = N'en')

INSERT INTO [dbo].[Traduccion] ([ID_Idioma], [ID_Etiqueta], [Texto])
SELECT @es, e.[ID], t.[Es] FROM @Textos t
INNER JOIN [dbo].[Etiqueta] e ON e.[Clave] = t.[Clave]
WHERE NOT EXISTS (SELECT 1 FROM [dbo].[Traduccion] x WHERE x.[ID_Idioma] = @es AND x.[ID_Etiqueta] = e.[ID])

INSERT INTO [dbo].[Traduccion] ([ID_Idioma], [ID_Etiqueta], [Texto])
SELECT @en, e.[ID], t.[En] FROM @Textos t
INNER JOIN [dbo].[Etiqueta] e ON e.[Clave] = t.[Clave]
WHERE NOT EXISTS (SELECT 1 FROM [dbo].[Traduccion] x WHERE x.[ID_Idioma] = @en AND x.[ID_Etiqueta] = e.[ID])
