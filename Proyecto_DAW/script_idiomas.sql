/* ---------- 3c. IDIOMAS CREADOS DESDE LA PÁGINA: textos faltantes como pendientes "[...]" ---------- */
INSERT INTO [dbo].[Traduccion] ([ID_Idioma], [ID_Etiqueta], [Texto])
SELECT i.[ID], tp.[ID_Etiqueta], N'[' + LEFT(tp.[Texto], 998) + N']'
FROM [dbo].[Idioma] i
CROSS JOIN [dbo].[Traduccion] tp
WHERE i.[Codigo] NOT IN (N'es', N'en')
  AND tp.[ID_Idioma] = (SELECT [ID] FROM [dbo].[Idioma] WHERE [EsPredeterminado] = 1)
  AND NOT EXISTS (SELECT 1 FROM [dbo].[Traduccion] x WHERE x.[ID_Idioma] = i.[ID] AND x.[ID_Etiqueta] = tp.[ID_Etiqueta])
GO

